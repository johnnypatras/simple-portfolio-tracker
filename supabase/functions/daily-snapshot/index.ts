async function fetchCoinGeckoPrices(
  coinIds: string[]
): Promise<Record<string, { usd: number; eur: number }>> {
  if (coinIds.length === 0) return {};
  try {
    const ids = coinIds.join(",");
    const url = `${COINGECKO_URL}?ids=${ids}&vs_currencies=usd,eur`;
    const headers: Record<string, string> = {};
    if (COINGECKO_API_KEY) headers["x-cg-demo-api-key"] = COINGECKO_API_KEY;

    let res = await fetchT(url, { headers });
    if (res.status === 429) {
      console.warn("[daily-snapshot] CoinGecko 429, retrying in 2s…");
      await new Promise((r) => setTimeout(r, 2000));
      res = await fetchT(url, { headers });
    }
    if (!res.ok) {
      console.error("[daily-snapshot] CoinGecko error:", res.status);
      Sentry.captureMessage("daily-snapshot: CoinGecko batch returned non-2xx", {
        level: "error",
        tags: { function: "daily-snapshot", phase: "coingecko_batch" },
        extra: { status: res.status, coinIdCount: coinIds.length },
      });
      return {};
    }
    return await res.json();
  } catch (err) {
    console.error("[daily-snapshot] CoinGecko fetch error:", err);
    Sentry.captureException(err, {
      tags: { function: "daily-snapshot", phase: "coingecko_batch" },
      extra: { coinIdCount: coinIds.length },
    });
    return {};
  }
}

async function getYahooCrumb(): Promise<{ crumb: string; cookie: string } | null> {
  try {
    // Step 1: Get session cookies
    const cookieRes = await fetchT("https://fc.yahoo.com/", {
      headers: { "User-Agent": "Mozilla/5.0" },
      redirect: "manual",
    });
    const setCookies = cookieRes.headers.getSetCookie?.() ?? [];
    const cookie = setCookies.map((c) => c.split(";")[0]).filter(Boolean).join("; ");
    if (!cookie) return null;

    // Step 2: Exchange cookies for crumb
    const crumbRes = await fetchT("https://query2.finance.yahoo.com/v1/test/getcrumb", {
      headers: { "User-Agent": "Mozilla/5.0", Cookie: cookie },
    });
    if (!crumbRes.ok) return null;
    const crumb = await crumbRes.text();
    if (!crumb || crumb.includes("Unauthorized")) return null;

    return { crumb, cookie };
  } catch (err) {
    console.error("[daily-snapshot] Yahoo crumb error:", err);
    return null;
  }
}

async function fetchYahooBatch(
  symbols: string[]
): Promise<Map<string, YahooQuote>> {
  const map = new Map<string, YahooQuote>();
  if (symbols.length === 0) return map;
  try {
    const auth = await getYahooCrumb();
    if (!auth) {
      console.error("[daily-snapshot] Yahoo crumb auth failed");
      Sentry.captureMessage("daily-snapshot: Yahoo crumb auth failed", {
        level: "error",
        tags: { function: "daily-snapshot", phase: "yahoo_crumb" },
        extra: { tickerCount: symbols.length },
      });
      return map;
    }

    const url = `${YAHOO_QUOTE_URL}?symbols=${symbols.join(",")}&crumb=${encodeURIComponent(auth.crumb)}`;
    const res = await fetchT(url, {
      headers: { "User-Agent": "Mozilla/5.0", Cookie: auth.cookie },
    });
    if (!res.ok) {
      console.error("[daily-snapshot] Yahoo error:", res.status);
      Sentry.captureMessage("daily-snapshot: Yahoo batch returned non-2xx", {
        level: "error",
        tags: { function: "daily-snapshot", phase: "yahoo_batch" },
        extra: { status: res.status, tickerCount: symbols.length },
      });
      return map;
    }
    const ct = res.headers.get("content-type") ?? "";
    if (!ct.includes("application/json")) {
      console.warn("[daily-snapshot] Yahoo batch returned non-JSON (captcha?), content-type:", ct);
      Sentry.captureMessage("daily-snapshot: Yahoo batch returned non-JSON (captcha?)", {
        level: "warning",
        tags: { function: "daily-snapshot", phase: "yahoo_batch" },
        extra: { contentType: ct, tickerCount: symbols.length },
      });
      return map;
    }
    const json = await res.json();
    const quotes = json?.quoteResponse?.result;
    if (!Array.isArray(quotes)) return map;

    for (const q of quotes) {
      if (!q.symbol) continue;
      map.set(q.symbol, {
        price: q.regularMarketPrice ?? 0,
        currency: q.currency ?? "USD",
      });
    }
  } catch (err) {
    console.error("[daily-snapshot] Yahoo fetch error:", err);
    Sentry.captureException(err, {
      tags: { function: "daily-snapshot", phase: "yahoo_batch" },
      extra: { tickerCount: symbols.length },
    });
  }
  return map;
}

async function fetchYahooSingle(ticker: string): Promise<YahooQuote | null> {
  try {
    const url = `${YAHOO_CHART_URL}/${encodeURIComponent(ticker)}?interval=1d&range=1d`;
    const res = await fetchT(url, {
      headers: { "User-Agent": "Mozilla/5.0" },
    });
    if (!res.ok) return null;
    const ct = res.headers.get("content-type") ?? "";
    if (!ct.includes("application/json")) return null;
    const json = await res.json();
    const meta = json?.chart?.result?.[0]?.meta;
    if (!meta) return null;
    return {
      price: meta.regularMarketPrice ?? 0,
      currency: meta.currency ?? "USD",
    };
  } catch (err) {
    console.error(`[daily-snapshot] v8 fallback error for ${ticker}:`, err);
    return null;
  }
}

async function fetchFxRates(
  base: string,
  targets: string[]
): Promise<Record<string, number>> {
  const symbols = [...new Set(targets.filter((t) => t !== base))];
  if (symbols.length === 0) return { [base]: 1 };

  // Retry once on failure, then throw — snapshot with wrong FX is worse than no snapshot
  for (let attempt = 0; attempt < 2; attempt++) {
    try {
      const url = `${FRANKFURTER_URL}?base=${base}&symbols=${symbols.join(",")}`;
      const res = await fetchT(url);
      if (!res.ok) {
        if (attempt === 0) {
          console.warn(`[daily-snapshot] Frankfurter ${res.status}, retrying...`);
          continue;
        }
        throw new Error(`Frankfurter API returned ${res.status} for ${base}→${symbols.join(",")}`);
      }
      const data = await res.json();

      // Validate all requested rates are present
      for (const sym of symbols) {
        if (data.rates[sym] == null) {
          throw new Error(`Frankfurter returned no rate for ${base}→${sym}`);
        }
      }

      return { ...data.rates, [base]: 1 };
    } catch (err) {
      if (attempt === 0 && err instanceof TypeError) {
        console.warn("[daily-snapshot] FX network error, retrying...");
        continue;
      }
      throw err;
    }
  }

  throw new Error(`[daily-snapshot] FX retries exhausted for ${base}→${symbols.join(",")}`);
}

