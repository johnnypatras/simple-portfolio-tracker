// ─── Fetch timeout (matches app-side fetchWithTimeout pattern) ──

async function fetchT(url: string | URL | Request, init?: RequestInit, timeoutMs = 15_000): Promise<Response> {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    return await fetch(url, { ...init, signal: controller.signal });
  } finally {
    clearTimeout(timer);
  }
}

// ─── Types ─────────────────────────────────────────────────

interface UserHoldings {
  userId: string;
  cryptoAssets: { coingecko_id: string; subcategory: string | null; quantity: number }[];
  stockAssets: { asset_id: string; yahoo_ticker: string; ticker: string; currency: string; quantity: number; kind: "yahoo" | "manual" }[];
  cashItems: { currency: string; amount: number }[];
}

interface YahooQuote {
  price: number;
  currency: string;
}

// ─── Main handler ──────────────────────────────────────────

Deno.serve(async (req: Request) => {
  // Validate required env vars at call time so misconfigured deploys
  // surface as HTTP 500 "Misconfigured" rather than isolate crashes.
  if (!SUPABASE_URL || !SUPABASE_SERVICE_ROLE_KEY) {
    console.error("[daily-snapshot] Missing SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY env var");
    // Nothing to flush here (Sentry can't init without DSN/transport set up
    // first), but if anyone adds a `Sentry.captureMessage("Misconfigured")`
    // above, this flush guarantees it lands before the isolate exits.
    await Sentry.flush(2000);
    return new Response("Misconfigured", { status: 500 });
  }

  // Fast reject before the DB round-trip when the caller didn't supply any
  // bearer credentials — this avoids wasting a query on health probes
  // and unauthenticated scans.
  const authHeader = req.headers.get("Authorization") ?? "";
  if (!authHeader.startsWith("Bearer ")) {
    await Sentry.flush(2000);
    return new Response("Unauthorized", { status: 401 });
  }

  const supabase = createClient(SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY);

  // Auth check — read secret from DB (auto-generated by migration 052, never in git)
  const { data: configRow } = await supabase
    .from("cron_config")
    .select("value")
    .eq("key", "cron_secret")
    .single();

  // Timing-safe secret comparison. Plain `!==` leaks per-byte timing that an
  // attacker could exploit to recover the cron_secret one character at a time.
  // Deno's Web Crypto subtle interface doesn't expose timingSafeEqual, so we
  // implement constant-time compare inline: short-circuit on length (length
  // alone is low-information for an opaque token), then XOR-accumulate across
  // all bytes regardless of mismatch position.
  if (!configRow?.value) {
    await Sentry.flush(2000);
    return new Response("Unauthorized", { status: 401 });
  }
  const expected = new TextEncoder().encode(`Bearer ${configRow.value}`);
  const received = new TextEncoder().encode(authHeader);
  let match = expected.length === received.length;
  if (match) {
    let diff = 0;
    for (let i = 0; i < expected.length; i++) diff |= expected[i] ^ received[i];
    match = diff === 0;
  }
  if (!match) {
    await Sentry.flush(2000);
    return new Response("Unauthorized", { status: 401 });
  }

  // Per-invocation correlation: lets operators trace a single cron tick
  // across all Sentry events, Supabase logs, and the HTTP response payload.
  // Each Deno.serve invocation runs in its own async context, so tags set
  // here are scoped to this invocation via Sentry's OTel context manager.
  const runId = crypto.randomUUID();
  Sentry.setTag("function", "daily-snapshot");
  Sentry.setTag("cron_run_id", runId);
  const startedAt = Date.now();

  try {

    // 1. Fetch all active users
    const { data: users, error: usersErr } = await supabase
      .from("profiles")
      .select("id")
      .eq("status", "active");

    if (usersErr) throw new Error(`Failed to fetch users: ${usersErr.message}`);
    if (!users || users.length === 0) {
      await Sentry.flush(2000);
      return jsonResponse({ message: "No active users", snapshots: 0, runId });
    }

    Sentry.addBreadcrumb({
      category: "snapshot",
      message: "Active users loaded",
      data: { count: users.length },
      level: "info",
    });

    const userIds = users.map((u: { id: string }) => u.id);

    // 2. Bulk-fetch all holdings across all users (service-role bypasses RLS)
    const [
      { data: cryptoAssets },
      { data: cryptoPositions },
      { data: stockAssets },
      { data: stockPositions },
      { data: cashAccounts },
    ] = await Promise.all([
      supabase.from("crypto_assets").select("id, user_id, coingecko_id, subcategory").is("deleted_at", null).in("user_id", userIds),
      supabase.from("crypto_positions").select("id, crypto_asset_id, quantity").is("deleted_at", null),
      supabase.from("stock_assets").select("id, user_id, ticker, yahoo_ticker, currency, kind").is("deleted_at", null).in("user_id", userIds),
      supabase.from("stock_positions").select("id, stock_asset_id, quantity").is("deleted_at", null),
      supabase.from("cash_accounts").select("user_id, currency, balance").is("deleted_at", null).in("user_id", userIds),
    ]);

    // 3. Build per-user holdings and deduplicated price request sets
    const coinIdSet = new Set<string>();
    const yahooTickerSet = new Set<string>();
    // currencySet seeds USD+EUR so the parallel FX fetches always include the
    // cross-rate between the two written columns; heldCurrenciesSet tracks
    // ONLY currencies that actually appear on user holdings — the abort guard
    // below uses this to detect "FX required but unavailable" precisely.
    const currencySet = new Set<string>(["USD", "EUR"]);
    const heldCurrenciesSet = new Set<string>();

    // Index crypto positions by asset ID
    const positionsByAsset = new Map<string, number>();
    for (const p of cryptoPositions ?? []) {
      const current = positionsByAsset.get(p.crypto_asset_id) ?? 0;
      positionsByAsset.set(p.crypto_asset_id, current + Number(p.quantity));
    }

    // Index stock positions by asset ID
    const stockPosByAsset = new Map<string, number>();
    for (const p of stockPositions ?? []) {
      const current = stockPosByAsset.get(p.stock_asset_id) ?? 0;
      stockPosByAsset.set(p.stock_asset_id, current + Number(p.quantity));
    }

    // Build per-user holdings
    const userHoldings = new Map<string, UserHoldings>();
    for (const userId of userIds) {
      userHoldings.set(userId, {
        userId,
        cryptoAssets: [],
        stockAssets: [],
        cashItems: [],
      });
    }

    // Crypto assets
    for (const asset of cryptoAssets ?? []) {
      const qty = positionsByAsset.get(asset.id) ?? 0;
      if (qty === 0) continue;
      coinIdSet.add(asset.coingecko_id);
      const holdings = userHoldings.get(asset.user_id);
      if (holdings) {
        holdings.cryptoAssets.push({
          coingecko_id: asset.coingecko_id,
          subcategory: asset.subcategory,
          quantity: qty,
        });
      }
    }

    // Stock assets — kind='yahoo' get added to yahooTickerSet for the Yahoo batch;
    // kind='manual' are looked up from manual_nav_updates below (no Yahoo fetch).
    for (const asset of stockAssets ?? []) {
      const qty = stockPosByAsset.get(asset.id) ?? 0;
      if (qty === 0) continue;
      const kind = (asset.kind as "yahoo" | "manual") ?? "yahoo";
      const yahooTicker = asset.yahoo_ticker || asset.ticker;
      if (kind === "yahoo") {
        yahooTickerSet.add(yahooTicker);
      }
      currencySet.add(asset.currency);
      heldCurrenciesSet.add(asset.currency);
      const holdings = userHoldings.get(asset.user_id);
      if (holdings) {
        holdings.stockAssets.push({
          asset_id: asset.id,
          yahoo_ticker: yahooTicker,
          ticker: asset.ticker,
          currency: asset.currency,
          quantity: qty,
          kind,
        });
      }
    }

    // Cash items (unified cash_accounts table)
    for (const acct of cashAccounts ?? []) {
      const amt = Number(acct.balance);
      if (amt === 0) continue;
      currencySet.add(acct.currency);
      heldCurrenciesSet.add(acct.currency);
      const holdings = userHoldings.get(acct.user_id);
      if (holdings) holdings.cashItems.push({ currency: acct.currency, amount: amt });
    }

    // 4. Batch price fetches (4 API calls in parallel)
    const allTickers = [...yahooTickerSet];
    const heldCurrencies = [...heldCurrenciesSet];
    const settled = await Promise.allSettled([
      fetchCoinGeckoPrices([...coinIdSet]),
      fetchYahooBatch(allTickers),
      fetchFxRates("USD", [...currencySet].filter((c) => c !== "USD")),
      fetchFxRates("EUR", [...currencySet].filter((c) => c !== "EUR")),
    ]);
    const [cryptoSettled, yahooSettled, fxUsdSettled, fxEurSettled] = settled;

    // Both snapshot columns (USD + EUR totals) are ALWAYS written, so:
    //   - the USD column needs fxUsd whenever any held currency != "USD"
    //   - the EUR column needs fxEur whenever any held currency != "EUR"
    // For a EUR-primary user holding USD assets (heldCurrencies=["USD"]),
    // needsEurFx=true → if fxEurFailed we must abort. The earlier guard only
    // checked `nonUsdEurCurrencies` (currencies other than USD AND EUR), so
    // pure USD- or pure EUR-asset users were left to silently corrupt their
    // snapshots when convertToBase() fell back to the unconverted amount.
    const fxUsdFailed = fxUsdSettled.status === "rejected";
    const fxEurFailed = fxEurSettled.status === "rejected";
    const needsUsdFx = heldCurrencies.some((c) => c !== "USD");
    const needsEurFx = heldCurrencies.some((c) => c !== "EUR");
    const fxUsdNeededButFailed = fxUsdFailed && needsUsdFx;
    const fxEurNeededButFailed = fxEurFailed && needsEurFx;
    if (fxUsdNeededButFailed || fxEurNeededButFailed) {
      const reason = fxUsdNeededButFailed
        ? (fxUsdSettled as PromiseRejectedResult).reason
        : (fxEurSettled as PromiseRejectedResult).reason;
      console.error(
        `[daily-snapshot] FX fetch failed with FX-dependent holdings in scope (held=${heldCurrencies.join(",")}, needsUsd=${needsUsdFx}, needsEur=${needsEurFx}) — aborting to avoid corrupt snapshots.`,
        reason,
      );
      Sentry.captureMessage(
        "Daily snapshot aborted: FX fetch failed with FX-dependent holdings in scope",
        {
          level: "error",
          extra: {
            fxUsdFailed,
            fxEurFailed,
            needsUsdFx,
            needsEurFx,
            heldCurrencies,
            reason: String(reason),
          },
        },
      );
      await Sentry.flush(2000);
      return jsonResponse(
        { error: "fx_unavailable", heldCurrencies, runId },
        503,
      );
    }

    // Surface rejected price fetches to Sentry so a sustained outage on
    // CoinGecko or Yahoo doesn't silently degrade snapshots to $0 for one
    // asset class. Both fall back to empty data — abort is reserved for FX
    // because empty crypto/yahoo only zeros THAT asset class (the
    // $0-with-prev-positive guard later may catch it for affected users).
    if (cryptoSettled.status === "rejected") {
      Sentry.captureException(cryptoSettled.reason, {
        tags: { function: "daily-snapshot", phase: "coingecko_batch" },
        extra: { runId, coinIdCount: coinIdSet.size },
      });
    }
    if (yahooSettled.status === "rejected") {
      Sentry.captureException(yahooSettled.reason, {
        tags: { function: "daily-snapshot", phase: "yahoo_batch" },
        extra: { runId, tickerCount: allTickers.length },
      });
    }

    const cryptoPrices = cryptoSettled.status === "fulfilled"
      ? cryptoSettled.value
      : ({} as Record<string, { usd: number; eur: number }>);
    const yahooQuotes = yahooSettled.status === "fulfilled"
      ? yahooSettled.value
      : new Map<string, YahooQuote>();
    const fxUsd = fxUsdSettled.status === "fulfilled"
      ? fxUsdSettled.value
      : ({ USD: 1 } as Record<string, number>);
    const fxEur = fxEurSettled.status === "fulfilled"
      ? fxEurSettled.value
      : ({ EUR: 1 } as Record<string, number>);

    // 4b. Fall back to v8/chart for any tickers missing from v7 batch.
    // Bail out of the remaining chunks if cumulative elapsed time approaches
    // the Edge Function wall-clock budget — partial ticker coverage is
    // preferable to the whole run timing out.
    const missingTickers = allTickers.filter((t) => !yahooQuotes.has(t));
    const v8StartedAt = Date.now();
    const V8_BUDGET_MS = 90_000; // generous cap well under platform 150s free limit
    if (missingTickers.length > 0) {
      console.log(`[daily-snapshot] v7 missing ${missingTickers.length} tickers, falling back to v8/chart`);
      const CHUNK_SIZE = 20;
      for (let i = 0; i < missingTickers.length; i += CHUNK_SIZE) {
        if (Date.now() - v8StartedAt > V8_BUDGET_MS) {
          const remaining = missingTickers.length - i;
          console.warn(`[daily-snapshot] v8 fallback budget exhausted — skipping ${remaining} tickers`);
          // captureMessage (not breadcrumb) so the event reaches Sentry even
          // when the rest of the run succeeds — otherwise silently-skipped
          // tickers cause user-visible snapshot dips with no signal.
          Sentry.captureMessage("daily-snapshot: v8 fallback budget exhausted", {
            level: "warning",
            tags: { function: "daily-snapshot", phase: "yahoo_v8_fallback" },
            extra: {
              runId,
              processed: i,
              skipped: remaining,
              totalMissing: missingTickers.length,
            },
          });
          break;
        }
        const chunk = missingTickers.slice(i, i + CHUNK_SIZE);
        const results = await Promise.allSettled(
          chunk.map((ticker) => fetchYahooSingle(ticker))
        );
        results.forEach((result, j) => {
          if (result.status === "fulfilled" && result.value) {
            yahooQuotes.set(chunk[j], result.value);
          }
        });
      }
    }

    // 5. Compute snapshots for each user
    const today = new Date().toISOString().split("T")[0];

    // Fetch latest manual NAV per (user_id, asset_id) as of `today`. Service-
    // role bypasses RLS so a single batched query covers all users. JS-side
    // groupBy keeps "max effective_date per (user, asset)" since the SQL
    // function get_latest_manual_navs_at takes a single user_id per call.
    // Defense: destructure and throw on error so a silent fetch failure
    // doesn't silently write wrong snapshots (manual contributions = 0) to
    // the entire fleet on the day the query breaks.
    const { data: manualNavsRaw, error: manualNavsErr } = await supabase
      .from("manual_nav_updates")
      .select("user_id, asset_id, effective_date, nav")
      .lte("effective_date", today)
      .in("user_id", userIds);

    if (manualNavsErr) {
      throw new Error(`Failed to load manual NAV history for cron: ${manualNavsErr.message}`);
    }

    const manualNavByUserAsset = new Map<string, number>(); // `${user_id}:${asset_id}` → latest nav
    const manualNavMaxDate = new Map<string, string>();
    for (const row of (manualNavsRaw ?? [])) {
      const key = `${row.user_id}:${row.asset_id}`;
      const prevDate = manualNavMaxDate.get(key);
      if (!prevDate || row.effective_date > prevDate) {
        manualNavMaxDate.set(key, row.effective_date);
        manualNavByUserAsset.set(key, Number(row.nav));
      }
    }
    const snapshots: {
      user_id: string;
      snapshot_date: string;
      created_at: string;
      total_value_usd: number;
      total_value_eur: number;
      crypto_value_usd: number;
      stocks_value_usd: number;
      cash_value_usd: number;
      crypto_value_eur: number;
      stocks_value_eur: number;
      cash_value_eur: number;
      stocks_eur_denominated_value: number;
      cash_eur_denominated_value: number;
    }[] = [];

    for (const [userId, holdings] of userHoldings) {
      let cryptoValueUsd = 0;
      let cryptoValueEur = 0;
      let stablecoinValueUsd = 0;
      let stablecoinValueEur = 0;

      // Crypto values (CoinGecko gives USD + EUR directly)
      for (const asset of holdings.cryptoAssets) {
        const price = cryptoPrices[asset.coingecko_id];
        if (!price) continue;
        const isStable = asset.subcategory?.toLowerCase() === "stablecoin";
        if (isStable) {
          stablecoinValueUsd += asset.quantity * (price.usd ?? 0);
          stablecoinValueEur += asset.quantity * (price.eur ?? 0);
        } else {
          cryptoValueUsd += asset.quantity * (price.usd ?? 0);
          cryptoValueEur += asset.quantity * (price.eur ?? 0);
        }
      }

      // Stock values (convert native currency → USD and EUR via FX).
      // kind='yahoo' → look up yahooQuotes (batch-fetched);
      // kind='manual' → look up latest NAV from manual_nav_updates.
      // Assets with no NAV history yet (manual+empty) silently contribute 0.
      let stocksValueUsd = 0;
      let stocksValueEur = 0;
      let stocksHomeCurrencyEur = 0;
      for (const asset of holdings.stockAssets) {
        let priceNative: number | undefined;
        // Exhaustive dispatch on kind. The default branch should never fire
        // (DB CHECK in migration 018 enforces kind in {'yahoo','manual'}),
        // but defense-in-depth: an unknown kind silently skips the asset and
        // emits a log line for operational visibility instead of misrouting
        // to Yahoo / manual paths.
        switch (asset.kind) {
          case "manual":
            priceNative = manualNavByUserAsset.get(`${holdings.userId}:${asset.asset_id}`);
            break;
          case "yahoo":
            priceNative = yahooQuotes.get(asset.yahoo_ticker)?.price;
            break;
          default:
            console.warn(`[daily-snapshot] Unknown stock asset kind="${asset.kind}" for user ${holdings.userId}, asset ${asset.asset_id}; skipping`);
            Sentry.captureMessage("Unknown stock asset kind — DB CHECK invariant violated", {
              level: "error",
              extra: {
                kind: asset.kind,
                userId: holdings.userId,
                assetId: asset.asset_id,
                ticker: asset.ticker,
              },
            });
            continue;
        }
        if (priceNative === undefined) continue;
        const valueNative = asset.quantity * priceNative;
        stocksValueUsd += convertToBase(valueNative, asset.currency, "USD", fxUsd);
        stocksValueEur += convertToBase(valueNative, asset.currency, "EUR", fxEur);
        if (asset.currency === "EUR") {
          stocksHomeCurrencyEur += convertToBase(valueNative, asset.currency, "EUR", fxEur);
        }
      }

      // Cash values (convert each currency → USD and EUR via FX)
      let fiatCashValueUsd = 0;
      let fiatCashValueEur = 0;
      let cashHomeCurrencyEur = 0;
      for (const item of holdings.cashItems) {
        fiatCashValueUsd += convertToBase(item.amount, item.currency, "USD", fxUsd);
        fiatCashValueEur += convertToBase(item.amount, item.currency, "EUR", fxEur);
        if (item.currency === "EUR") {
          cashHomeCurrencyEur += convertToBase(item.amount, item.currency, "EUR", fxEur);
        }
      }

      // Cash = fiat + stablecoins (matching aggregate.ts logic)
      const cashValueUsd = fiatCashValueUsd + stablecoinValueUsd;
      const totalValueUsd = cryptoValueUsd + stocksValueUsd + cashValueUsd;
      const totalValueEur = cryptoValueEur + stocksValueEur + fiatCashValueEur + stablecoinValueEur;

      // Validation: component sum must match total (catches computation bugs)
      const roundedTotal = round2(totalValueUsd);
      const componentSum = round2(cryptoValueUsd + stocksValueUsd + cashValueUsd);
      const drift = Math.abs(roundedTotal - componentSum);
      if (drift > 1) {
        console.error(
          `[daily-snapshot] VALIDATION FAILED for ${userId}: total ($${roundedTotal}) ≠ components ($${componentSum}), drift $${drift}`
        );
        Sentry.captureMessage("Snapshot validation drift exceeded $1", {
          level: "error",
          extra: {
            userId,
            total: roundedTotal,
            componentSum,
            drift,
          },
        });
      }

      const hasHoldings = holdings.cryptoAssets.length > 0 || holdings.stockAssets.length > 0 || holdings.cashItems.length > 0;
      if (totalValueUsd === 0 && hasHoldings) {
        console.warn(
          `[daily-snapshot] SKIPPING ${userId}: $0 total but has holdings (crypto=${holdings.cryptoAssets.length}, stocks=${holdings.stockAssets.length}, cash=${holdings.cashItems.length}) — likely API failure`
        );
        Sentry.captureMessage("Snapshot skipped: $0 total with holdings (likely API failure)", {
          level: "warning",
          extra: {
            userId,
            cryptoCount: holdings.cryptoAssets.length,
            stockCount: holdings.stockAssets.length,
            cashCount: holdings.cashItems.length,
          },
        });
        continue;
      }

      snapshots.push({
        user_id: userId,
        snapshot_date: today,
        created_at: new Date().toISOString(),
        total_value_usd: round2(totalValueUsd),
        total_value_eur: round2(totalValueEur),
        crypto_value_usd: round2(cryptoValueUsd),
        stocks_value_usd: round2(stocksValueUsd),
        cash_value_usd: round2(cashValueUsd),
        crypto_value_eur: round2(cryptoValueEur),
        stocks_value_eur: round2(stocksValueEur),
        cash_value_eur: round2(fiatCashValueEur + stablecoinValueEur),
        stocks_eur_denominated_value: round2(stocksHomeCurrencyEur),
        cash_eur_denominated_value: round2(cashHomeCurrencyEur),
      });
    }

    // 6. Batch upsert all snapshots
    if (snapshots.length > 0) {
      const { error: upsertErr } = await supabase
        .from("portfolio_snapshots")
        .upsert(snapshots, { onConflict: "user_id,snapshot_date" });

      if (upsertErr) throw new Error(`Upsert failed: ${upsertErr.message}`);
    }

    Sentry.addBreadcrumb({
      category: "snapshot",
      message: "Snapshots upserted",
      data: {
        count: snapshots.length,
        coins: coinIdSet.size,
        stocks: yahooTickerSet.size,
        currencies: currencySet.size,
        v8Fallback: missingTickers.length,
        elapsedMs: Date.now() - startedAt,
      },
      level: "info",
    });
    await Sentry.flush(2000);

    return jsonResponse({
      message: "Snapshots saved",
      snapshots: snapshots.length,
      prices: { coins: coinIdSet.size, stocks: yahooTickerSet.size, currencies: currencySet.size },
      v8Fallback: missingTickers.length,
      runId,
    });
  } catch (err) {
    Sentry.captureException(err);
    // Full error details (which may include DB constraint names or other
    // schema fingerprints) are logged + sent to Sentry. The HTTP response
    // returns only a generic code + runId so the caller can correlate the
    // failure with Sentry without us leaking schema details via response
    // bodies (which are not marked private and could be cached upstream).
    console.error(`[daily-snapshot] Error (run ${runId}):`, err);
    await Sentry.flush(2000);
    return jsonResponse({ error: "internal_error", runId }, 500);
  }
});

